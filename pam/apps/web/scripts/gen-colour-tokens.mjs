#!/usr/bin/env node
/**
 * Writes `src/stories/foundations/colourTokens.generated.ts`: every `--color-*` token in the theme
 * (`packages/ui/src/theme/pam.css`), for Foundations › Colour (D-504). Run after the theme changes:
 *
 *   pnpm --filter @pam/web tokens:colours
 *
 * A unit test fails when the file is out of step with the theme, so the Colour page cannot go stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseColourTokens } from '../src/stories/foundations/colourTokens.ts';

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(join(here, '..', '..', '..', 'packages', 'ui', 'src', 'theme', 'pam.css'), 'utf8');
const tokens = parseColourTokens(css);
const body = `/* Generated by scripts/gen-colour-tokens.mjs from the theme: do not edit. D-504. */
import type { ColourToken } from './colourTokens';

export const COLOUR_TOKENS: readonly ColourToken[] = ${JSON.stringify(tokens, null, 2)};
`;
writeFileSync(join(here, '..', 'src', 'stories', 'foundations', 'colourTokens.generated.ts'), body);
console.log(`${tokens.length} colour tokens written`);
